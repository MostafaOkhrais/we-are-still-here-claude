// Static HTML for the team and shop lists, written into team.html and shop.html by scripts/build-ar.mjs.
//
// Crawlers that do not run JavaScript (most AI crawlers) then see every name and product. The markup matches what
// public/js/team.js and shop.js build in the browser (those scripts replace it on load), without the entrance
// animation, which needs JavaScript. English text plus data-ar, so build-ar.mjs translates it like the rest of the page.

export const TEAM_START = '<!-- prerender:team:start (generated by scripts/prerender.mjs) -->';
export const TEAM_END = '<!-- prerender:team:end -->';
export const SHOP_START = '<!-- prerender:shop:start (generated by scripts/prerender.mjs) -->';
export const SHOP_END = '<!-- prerender:shop:end -->';

const esc = (t) => String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const tx = (ar, en) => ' data-ar="' + esc(ar) + '" data-en="' + esc(en) + '">' + esc(en);

function member(m) {
  const alt = m.alt ? m.alt : m.nameEn;
  return '<div class="group bg-white rounded-[20px] border border-cream-line overflow-hidden shadow-soft hover:shadow-card hover:-translate-y-1 transition text-center">' +
    '<div class="aspect-[3/4] overflow-hidden relative">' +
    '<img src="' + esc(m.photo) + '" width="600" height="800" loading="lazy" data-ar-alt="' + esc(m.nameAr) + '" data-en-alt="' + esc(alt) + '" alt="' + esc(alt) + '" class="w-full h-full object-cover group-hover:scale-105 transition duration-500">' +
    '<div class="absolute inset-x-0 bottom-0 h-20 bg-gradient-to-t from-black/50 to-transparent"></div></div>' +
    '<div class="p-3 sm:p-5">' +
    '<h3 class="font-extrabold text-sm sm:text-[15px] leading-snug"' + tx(m.nameAr, m.nameEn) + '</h3>' +
    '<p class="mt-1.5 inline-flex items-center justify-center bg-olive-soft text-olive-dark text-xs font-bold px-3 py-1 rounded-full"' + tx(m.roleAr, m.roleEn) + '</p>' +
    '</div></div>';
}

export function teamHtml(team) {
  return team.departments.map((d) =>
    '\n<section><div class="flex items-center gap-3 mb-6">' +
    '<span class="w-10 h-10 rounded-xl ' + esc(d.badge) + ' flex items-center justify-center font-black text-sm">' + esc(d.num) + '</span>' +
    '<h2 class="text-[20px] lg:text-[22px] font-black"' + tx(d.titleAr, d.titleEn) + '</h2>' +
    '<span class="h-px flex-1 bg-cream-line ms-4 hidden sm:block"></span></div>' +
    '<div class="grid grid-cols-2 md:grid-cols-3 lg:grid-cols-4 gap-3 sm:gap-5">' + d.members.map(member).join('') + '</div></section>'
  ).join('') + '\n';
}

const EXTERNAL = '<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true"><path d="M18 13v6a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h6"/><polyline points="15 3 21 3 21 9"/><line x1="10" y1="14" x2="21" y2="3"/></svg>';

function product(p, idx, base) {
  const href = esc(base + p.slug + '/');
  const eager = idx < 3;
  return '\n<div class="group bg-white rounded-[24px] border border-cream-line overflow-hidden shadow-soft hover:shadow-card hover:-translate-y-1 transition flex flex-col">' +
    '<a href="' + href + '" target="_blank" rel="noopener noreferrer" class="relative block aspect-square bg-cream border-b border-cream-line overflow-hidden" data-ar-label="' + esc(p.nameAr) + '" data-en-label="' + esc(p.name) + '" aria-label="' + esc(p.name) + '">' +
    '<img src="' + esc(p.img) + '" data-ar-alt="' + esc(p.nameAr) + '" data-en-alt="' + esc(p.name) + '" alt="' + esc(p.name) + '" loading="' + (eager ? 'eager' : 'lazy') + '" decoding="async" width="640" height="640"' + (eager ? ' fetchpriority="high"' : '') + ' class="w-full h-full object-cover group-hover:scale-105 transition duration-500">' +
    '<span class="absolute bottom-2 end-2 sm:bottom-3 sm:end-3 bg-olive text-white text-xs sm:text-sm font-extrabold px-3 sm:px-4 py-1 sm:py-1.5 rounded-full shadow-soft" dir="ltr">&pound;' + esc(p.price) + '</span></a>' +
    '<div class="p-3 sm:p-5 flex flex-col flex-1">' +
    '<h3 class="font-extrabold text-sm sm:text-[15px] leading-snug sm:leading-6"' + tx(p.nameAr, p.name) + '</h3>' +
    '<p class="mt-2 text-xs font-bold text-gold-deep"' + tx(p.typeAr, p.type) + '</p>' +
    '<a href="' + href + '" target="_blank" rel="noopener noreferrer" class="mt-3 sm:mt-4 inline-flex items-center justify-center gap-2 bg-olive hover:bg-olive-dark text-white px-3 sm:px-6 py-3 rounded-full font-bold text-sm transition w-full">' +
    '<span' + tx('عرض المنتج', 'View product') + '</span>' + EXTERNAL + '</a>' +
    '</div></div>';
}

export function shopHtml(shop) {
  return shop.products.map((p, i) => product(p, i, shop.base)).join('') + '\n';
}

// Replaces the generated block, or creates it inside the (empty) host element the first time.
export function insertBlock(html, host, start, end, content) {
  const block = start + content + end;
  const a = html.indexOf(start);
  const b = html.indexOf(end);
  if (a >= 0 && b > a) return html.slice(0, a) + block + html.slice(b + end.length);
  if (!html.includes(host + '</div>')) throw new Error('prerender host not found: ' + host);
  return html.replace(host + '</div>', () => host + block + '</div>');
}
